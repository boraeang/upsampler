DEFAULT_MIN_OOS = 20
"""Minimum out-of-sample errors for a pool to be used as an empirical law."""

IntervalMethod = Literal["empirical_recursive", "empirical_direct", "parametric"]

InnovationSampler = Callable[[int, int, np.random.Generator], np.ndarray]
"""``(step_horizon, size, rng) -> innovations`` — see :func:`recursive_predictive_draws`."""


class ResidualPoolWarning(UserWarning):
    """Emitted when a predictive distribution rests on a weaker basis than asked."""


