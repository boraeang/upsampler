r"""
Predictive distributions for nowcasts: residual pools and recursive simulation.

Three mechanisms, in the order you should prefer them.

``'empirical_recursive'`` (default for models with dynamics)
    The innovation distribution is the model's own **out-of-sample** one-step
    rolling-origin errors, estimated inside the information set by
    :func:`rolling_origin_backtest`. Multi-quarter horizons are handled by
    simulation: draw ``s_Q`` from its predictive distribution, re-evaluate the
    conditional mean of ``s_{Q+1}`` at *each draw*, and add a fresh innovation.
    The horizon widening is then generated by the model's own dynamics rather
    than asserted.

``'empirical_direct'`` (default for models without dynamics)
    The predictive distribution at horizon ``h`` is the point nowcast plus a
    resample of the out-of-sample errors *at that same horizon*. Appropriate
    when the model has no internal dynamics to propagate — a carry-forward
    baseline — and useful everywhere as a cross-check (see below).

``'parametric'``
    Gaussian with the regression's prediction variance
    :math:`\hat\sigma^2 (1 + x'(X'X)^{-1}x)`, optionally convolved with
    posterior parameter uncertainty. Narrower and smoother than the empirical
    pools, and wrong in the left tail of real private markets data.

Why recursion uses the one-step pool
------------------------------------
The module spec asks for two things that pull against each other: residuals
drawn from the out-of-sample errors *at the same horizon*, and recursive
simulation for ``h >= 2``. Doing both at once double counts — the historical
``h=2`` errors were themselves produced by a nowcast that plugged in an ``h=1``
nowcast, so they already contain the accumulated uncertainty that the recursion
is about to add again.

The resolution here: recursion is the mechanism, and the innovation at *every*
step of the recursion is drawn from the **one-step** pool. For the smoothing
regression :math:`s_Q = a + b F_Q + c\, s_{Q-1} + e_Q` this reproduces the
analytic answer exactly — :math:`\mathrm{Var}(h{=}2) = \sigma_e^2 (1 + c^2)`,
so with :math:`c = \lambda \approx 0.6` the ``h=2`` interval is about 17 %
wider — without any double counting.

The literal horizon-matched reading remains available as
``'empirical_direct'``, and is not merely a fallback: recursion with i.i.d.
one-step innovations assumes the model is correctly specified, whereas the
direct pool absorbs compounding misspecification. Every recursive result
therefore carries ``diagnostics['interval_80_direct']`` when a direct pool
exists, so a materially wider direct interval is visible as a misspecification
signal instead of being hidden by the choice of method.

The pool is not centred
-----------------------
Out-of-sample errors in a small sample have a non-zero mean, and that mean is
kept. The spec's wording — "point forecast + residuals drawn from that model's
own out-of-sample rolling-origin errors" — is taken literally: the predictive
distribution answers "where will the realisation fall", and the model's own
historical bias is part of that answer. The consequence is that ``point`` is the
model's raw forecast while the draws sit ``mean(pool)`` away from it, so
``point`` is not the centre of its own interval.

That is deliberate, and the alternative is worse: centring the pool would
silently bias-correct the point forecast's *interval* while leaving the point
forecast itself uncorrected, which is the least coherent of the three options.
Every result therefore carries ``diagnostics['pool_mean']`` so the gap is
visible and attributable, and the evaluation harness reports mean error as a
separate metric rather than letting it hide inside the interval.

Small-sample fallback
---------------------
A pool with fewer than ``min_oos`` (default 20) out-of-sample errors is not an
empirical distribution, it is noise. Below that threshold the pool falls back to
in-sample residuals inflated by :math:`\sqrt{1 + p/n}` — the standard
degrees-of-freedom correction for the fact that in-sample residuals are
shrunk toward zero by the ``p`` fitted parameters — and the result's
``interval_method`` is suffixed ``'+in_sample_inflated'`` so the weaker basis
travels with the number.

References
----------
.. [1] Efron & Tibshirani (1993) — *An Introduction to the Bootstrap*, on
       resampling residuals for prediction intervals.
.. [2] Tashman (2000) — "Out-of-sample tests of forecasting accuracy,"
       *International Journal of Forecasting*. Rolling-origin evaluation.
"""

