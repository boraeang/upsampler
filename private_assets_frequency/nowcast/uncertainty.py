@dataclass(frozen=True)
class ResidualPool:
    """Per-horizon error distributions backing a model's prediction intervals.

    Attributes
    ----------
    errors
        ``{horizon: errors}``. Each array holds ``actual - predicted`` at that
        horizon, either from the rolling-origin backtest or — when too few of
        those exist — from inflated in-sample residuals.
    source
        ``{horizon: 'oos' | 'in_sample_inflated'}``.
    n_oos
        ``{horizon: n}`` out-of-sample errors actually available, *before* any
        fallback. The honest count.
    inflation
        The :math:`\\sqrt{1 + p/n}` factor applied to in-sample residuals.
    min_oos
        Threshold below which the fallback engaged.
    diagnostics
        Free-form provenance, surfaced in every ``NowcastResult``.
    """

    errors: dict[int, np.ndarray]
    source: dict[int, str]
    n_oos: dict[int, int]
    inflation: float
    min_oos: int
    diagnostics: dict[str, Any] = field(default_factory=dict)

    def has(self, horizon: int) -> bool:
        """Whether a pool exists for ``horizon``."""
        return horizon in self.errors and self.errors[horizon].size > 0

    def sample(
        self, horizon: int, size: int, rng: np.random.Generator
    ) -> np.ndarray:
        """Resample ``size`` innovations for ``horizon``, with replacement.

        Parameters
        ----------
        horizon
            Horizon whose pool to draw from.
        size
            Number of draws.
        rng
            Generator.

        Returns
        -------
        np.ndarray
            Shape ``(size,)``.

        Raises
        ------
        KeyError
            If no pool exists for ``horizon``. Callers check :meth:`has` first;
            there is no silent substitution of one horizon's errors for
            another's.
        """
        if not self.has(horizon):
            raise KeyError(
                f"no residual pool at horizon {horizon}; available: "
                f"{sorted(h for h in self.errors if self.errors[h].size)}."
            )
        pool = self.errors[horizon]
        return pool[rng.integers(0, pool.size, size=size)]

    def sampler(self, horizon: int) -> InnovationSampler:
        """A fixed-horizon innovation sampler for :func:`recursive_predictive_draws`.

        Parameters
        ----------
        horizon
            Horizon whose pool every call should draw from, regardless of the
            recursion step. Pass ``1`` for the one-step innovation law.

        Returns
        -------
        Callable
            ``(step_horizon, size, rng) -> np.ndarray``. ``step_horizon`` is
            accepted and ignored, which is the point: the recursion generates
            horizon widening through the model's dynamics, not by switching
            pools.
        """
        if not self.has(horizon):
            raise KeyError(f"no residual pool at horizon {horizon}.")

        def _sample(step_horizon: int, size: int, rng: np.random.Generator) -> np.ndarray:
            return self.sample(horizon, size, rng)

        return _sample

    def scale(self, horizon: int) -> float:
        """Standard deviation of the pool at ``horizon``."""
        if not self.has(horizon):
            raise KeyError(f"no residual pool at horizon {horizon}.")
        pool = self.errors[horizon]
        return float(np.std(pool, ddof=1)) if pool.size > 1 else float(abs(pool[0]))

    def is_fallback(self, horizon: int) -> bool:
        """Whether ``horizon`` is backed by inflated in-sample residuals."""
        return self.source.get(horizon) == "in_sample_inflated"

    def method_suffix(self, horizons: Sequence[int]) -> str:
        """``'+in_sample_inflated'`` if any of ``horizons`` used the fallback."""
        if any(self.is_fallback(h) for h in horizons):
            return "+in_sample_inflated"
        return ""


def build_residual_pool(
    oos_errors: dict[int, np.ndarray] | None,
    in_sample_residuals: np.ndarray,
    *,
    n_params: int,
    horizons: Sequence[int],
    min_oos: int = DEFAULT_MIN_OOS,
    warn: bool = True,
    label: str = "nowcaster",
) -> ResidualPool:
    r"""Assemble per-horizon error pools, falling back when the OOS count is thin.

    Parameters
    ----------
    oos_errors
        ``{horizon: errors}`` from :func:`rolling_origin_backtest`, or ``None``.
    in_sample_residuals
        Residuals of the final fit, used for the fallback.
    n_params
        Number of fitted parameters ``p``, for the
        :math:`\sqrt{1 + p/n}` inflation.
    horizons
        Horizons a pool is needed for.
    min_oos
        Below this many out-of-sample errors, fall back.
    warn
        Emit :class:`ResidualPoolWarning` when the fallback engages.
    label
        Model name, for the warning text.

    Returns
    -------
    ResidualPool

    Raises
    ------
    ValueError
        If neither out-of-sample errors nor usable in-sample residuals exist for
        a requested horizon — there is then no basis for an interval at all, and
        returning a point estimate dressed as a distribution would be worse.

    Notes
    -----
    The inflation factor corrects the *scale* of in-sample residuals but not
    their *shape*: they remain the residuals of a fit that saw the data, and
    they understate genuine forecast error from parameter instability and regime
    change. The suffix on ``interval_method`` exists so that caveat is visible
    downstream rather than only here.
    """
    resid = np.asarray(in_sample_residuals, dtype=float).reshape(-1)
    resid = resid[np.isfinite(resid)]
    n = resid.size
    inflation = float(np.sqrt(1.0 + n_params / n)) if n > 0 else float("nan")
    inflated = resid * inflation if n > 0 else resid

    errors: dict[int, np.ndarray] = {}
    source: dict[int, str] = {}
    n_oos: dict[int, int] = {}
    fell_back: list[int] = []

    for h in sorted(set(int(x) for x in horizons)):
        pool = (
            np.asarray(oos_errors.get(h, np.empty(0)), dtype=float).reshape(-1)
            if oos_errors
            else np.empty(0)
        )
        pool = pool[np.isfinite(pool)]
        n_oos[h] = int(pool.size)
        if pool.size >= min_oos:
            errors[h] = pool
            source[h] = "oos"
            continue
        if inflated.size == 0:
            raise ValueError(
                f"{label}: horizon {h} has {pool.size} out-of-sample errors "
                f"(need {min_oos}) and no usable in-sample residuals; there is "
                "no basis for a prediction interval."
            )
        errors[h] = inflated
        source[h] = "in_sample_inflated"
        fell_back.append(h)

    if fell_back and warn:
        warnings.warn(
            f"{label}: horizons {fell_back} have fewer than {min_oos} "
            "out-of-sample rolling-origin errors, so their prediction intervals "
            f"fall back to in-sample residuals inflated by sqrt(1 + p/n) = "
            f"{inflation:.3f}. In-sample residuals understate forecast error "
            "from parameter instability and regime change; treat the intervals "
            "as a lower bound on uncertainty.",
            ResidualPoolWarning,
            stacklevel=2,
        )

    return ResidualPool(
        errors=errors,
        source=source,
        n_oos=n_oos,
        inflation=inflation,
        min_oos=int(min_oos),
        diagnostics={
            "n_in_sample_residuals": int(n),
            "in_sample_inflation": inflation,
            "n_oos_by_horizon": dict(n_oos),
            "source_by_horizon": dict(source),
            "fallback_horizons": fell_back,
            "min_oos": int(min_oos),
        },
    )


# ──────────────────────────────────────────────────────────────────
# Rolling-origin backtest (inside an information set)
# ──────────────────────────────────────────────────────────────────


def rolling_origin_backtest(
    actual: np.ndarray,
    *,
    min_train: int,
    horizons: Sequence[int],
    predict_fn: Callable[[int, Sequence[int]], dict[int, float]],
    max_origins: int | None = None,
) -> tuple[dict[int, np.ndarray], dict[str, Any]]:
    r"""Expanding-window backtest producing out-of-sample errors by horizon.

    For each origin ``o`` the callable is given the number of training rows —
    rows ``[0, o)`` — and returns a nowcast for rows ``o, o+1, …`` at the
    requested horizons. The error at horizon ``h`` is
    ``actual[o + h - 1] - prediction[h]``.

    This runs **inside** an information set: ``actual`` holds published rows
    only, so no origin can see an unpublished quarter, and ``predict_fn`` is
    expected to re-estimate everything from ``[0, o)`` on each call. The
    expense is the point — reusing a single global fit is the leak this function
    exists to avoid.

    Parameters
    ----------
    actual
        Realised values, in time order.
    min_train
        Smallest training window. Origins start here.
    horizons
        Horizons to score.
    predict_fn
        ``predict_fn(n_train, horizons) -> {horizon: prediction}``. May return a
        partial mapping or ``NaN`` to decline an origin (e.g. a singular design);
        declined origins are counted in the diagnostics and skipped.
    max_origins
        Keep only the most recent ``max_origins`` origins. ``None`` uses all of
        them. Useful when ``predict_fn`` is expensive, at the cost of a thinner
        pool.

    Returns
    -------
    errors : dict[int, np.ndarray]
        Out-of-sample errors per horizon.
    diagnostics : dict
        Origin counts, skipped origins, and the training-window range.

    Notes
    -----
    Errors are *not* aligned across horizons: the ``h=1`` pool has one more
    entry than the ``h=2`` pool, because the last origin has no second target.
    Each pool is used independently, so this is harmless.
    """
    y = np.asarray(actual, dtype=float).reshape(-1)
    n = y.size
    hs = sorted(set(int(h) for h in horizons))
    if min_train < 1:
        raise ValueError(f"min_train must be >= 1, got {min_train}.")
    if not hs or min(hs) < 1:
        raise ValueError(f"horizons must all be >= 1, got {list(horizons)!r}.")

    origins = list(range(min_train, n))
    if max_origins is not None:
        if max_origins < 1:
            raise ValueError(f"max_origins must be >= 1, got {max_origins}.")
        origins = origins[-max_origins:]

    collected: dict[int, list[float]] = {h: [] for h in hs}
    n_skipped = 0
    n_declined: dict[int, int] = {h: 0 for h in hs}

    for o in origins:
        feasible = [h for h in hs if o + h - 1 < n]
        if not feasible:
            continue
        try:
            preds = predict_fn(o, feasible)
        except Exception:  # noqa: BLE001 - an origin may be unfittable
            n_skipped += 1
            continue
        if preds is None:
            n_skipped += 1
            continue
        for h in feasible:
            pred = preds.get(h, np.nan)
            if pred is None or not np.isfinite(pred):
                n_declined[h] += 1
                continue
            collected[h].append(float(y[o + h - 1] - pred))

    errors = {h: np.asarray(v, dtype=float) for h, v in collected.items()}
    diagnostics = {
        "n_origins_attempted": len(origins),
        "n_origins_skipped": n_skipped,
        "n_declined_by_horizon": n_declined,
        "n_errors_by_horizon": {h: int(v.size) for h, v in errors.items()},
        "min_train": int(min_train),
        "first_origin": origins[0] if origins else None,
        "last_origin": origins[-1] if origins else None,
        "n_rows": int(n),
    }
    return errors, diagnostics


