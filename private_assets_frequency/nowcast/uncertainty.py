def recursive_predictive_draws(
    *,
    horizons: Sequence[int],
    conditional_mean: Callable[[int, np.ndarray], np.ndarray],
    history: np.ndarray,
    innovation_sampler: InnovationSampler,
    n_draws: int,
    rng: np.random.Generator,
) -> dict[int, np.ndarray]:
    r"""Simulate the predictive distribution recursively across horizons.

    .. code-block:: text

        h = 1:  draws₁ = m(1, history)          + e₁
        h = 2:  draws₂ = m(2, [draws₁, history]) + e₂
        h = 3:  draws₃ = m(3, [draws₂, draws₁, …]) + e₃

    with every ``eₕ`` an independent resample of the one-step innovation pool.
    The conditional mean is re-evaluated at *each draw* rather than at the point
    forecast, which is what makes the ``h >= 2`` interval reflect the
    uncertainty in the ``h = 1`` value it conditions on.

    Parameters
    ----------
    horizons
        Horizons to simulate, which must be ``1, 2, …, H`` with no gaps: a
        recursion cannot skip a step, because horizon ``h`` conditions on
        horizon ``h - 1``.
    conditional_mean
        ``conditional_mean(horizon, history) -> np.ndarray`` of shape
        ``(n_draws,)``. ``history`` has shape ``(n_draws, n_lags)`` with column
        ``0`` the most recent reported value, column ``1`` the one before it,
        and so on. Must be vectorised over rows.
    history
        Initial lag history, shape ``(n_lags,)`` or ``(n_draws, n_lags)``. A 1-D
        array of known published values is broadcast across draws.
    innovation_sampler
        ``(step_horizon, size, rng) -> np.ndarray`` supplying the innovation
        added at each step. :meth:`ResidualPool.sampler` adapts an empirical
        pool — pass ``pool.sampler(1)`` for the one-step law, which is the
        default throughout this package and the reason the module docstring
        gives. A model with a parametric predictive variance supplies its own
        Gaussian sampler here instead.
    n_draws
        Number of draws.
    rng
        Generator.

    Returns
    -------
    draws : dict[int, np.ndarray]
        ``{horizon: draws}``, each of shape ``(n_draws,)``.

    See Also
    --------
    point_chain : the matching point forecast, which chains the same
        ``conditional_mean`` with zero innovations.

    Raises
    ------
    ValueError
        If ``horizons`` is not contiguous from 1, or shapes do not line up.
    """
    hs = sorted(set(int(h) for h in horizons))
    if hs != list(range(1, len(hs) + 1)):
        raise ValueError(
            "recursive simulation needs contiguous horizons 1..H (horizon h "
            f"conditions on h-1); got {hs}."
        )
    if n_draws < 1:
        raise ValueError(f"n_draws must be >= 1, got {n_draws}.")
    hist = np.asarray(history, dtype=float)
    if hist.ndim == 1:
        hist = np.tile(hist.reshape(1, -1), (n_draws, 1))
    elif hist.ndim == 2:
        if hist.shape[0] != n_draws:
            raise ValueError(
                f"history has {hist.shape[0]} rows but n_draws={n_draws}."
            )
        hist = hist.copy()
    else:
        raise ValueError(f"history must be 1-D or 2-D, got {hist.ndim}-D.")
    n_lags = hist.shape[1]

    draws: dict[int, np.ndarray] = {}

    for h in hs:
        mean = np.asarray(conditional_mean(h, hist), dtype=float).reshape(-1)
        if mean.size != n_draws:
            raise ValueError(
                f"conditional_mean at horizon {h} returned {mean.size} values, "
                f"expected {n_draws}."
            )
        drawn = mean + np.asarray(
            innovation_sampler(h, n_draws, rng), dtype=float
        ).reshape(-1)
        draws[h] = drawn
        if n_lags > 0:
            hist = np.concatenate(
                [drawn.reshape(-1, 1), hist[:, : n_lags - 1]], axis=1
            )

    return draws


def point_chain(
    *,
    horizons: Sequence[int],
    conditional_mean: Callable[[int, np.ndarray], np.ndarray],
    history: np.ndarray,
) -> dict[int, float]:
    """Point forecasts from chaining ``conditional_mean`` with zero innovations.

    The deterministic counterpart of :func:`recursive_predictive_draws`: horizon
    ``h`` conditions on the *point* forecast for ``h - 1`` rather than on a
    draw. For a linear conditional mean this is the conditional expectation, and
    therefore equals the mean of the simulated draws up to simulation error.

    Parameters
    ----------
    horizons
        Contiguous horizons ``1..H``.
    conditional_mean
        As in :func:`recursive_predictive_draws`, called with a single-row
        history.
    history
        Known lag history, shape ``(n_lags,)``.

    Returns
    -------
    dict[int, float]
        ``{horizon: point}``.
    """
    hs = sorted(set(int(h) for h in horizons))
    if hs != list(range(1, len(hs) + 1)):
        raise ValueError(f"point_chain needs contiguous horizons 1..H; got {hs}.")
    hist = np.asarray(history, dtype=float).reshape(1, -1)
    n_lags = hist.shape[1]
    points: dict[int, float] = {}
    for h in hs:
        mean = np.asarray(conditional_mean(h, hist), dtype=float).reshape(-1)
        points[h] = float(mean[0])
        if n_lags > 0:
            hist = np.concatenate(
                [np.array([[points[h]]]), hist[:, : n_lags - 1]], axis=1
            )
    return points


def empirical_interval(
    draws: np.ndarray, level: float = 0.80
) -> tuple[float, float]:
    """Equal-tailed empirical interval of ``draws`` at nominal ``level``.

    Parameters
    ----------
    draws
        Predictive draws.
    level
        Nominal coverage in ``(0, 1)``.

    Returns
    -------
    tuple[float, float]
        ``(lower, upper)``.
    """
    if not 0.0 < level < 1.0:
        raise ValueError(f"level must be in (0, 1), got {level!r}.")
    tail = (1.0 - level) / 2.0
    lo, hi = np.quantile(np.asarray(draws, dtype=float), [tail, 1.0 - tail])
    return float(lo), float(hi)
